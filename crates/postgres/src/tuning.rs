use std::{
    fmt::Write as _,
    fs::{self, OpenOptions},
    io::Write as _,
    num::NonZeroU32,
    path::Path,
};

use anyhow::{Context, Result};
use pgconfig::{Arch, Bytes, DiskType, Os, PgVersion, Profile, TuningRequest};
use sysinfo::{DiskKind, Disks, System};

const CONFIG_NAME: &str = "pioneer-tuning.conf";
// PGConfig 4.0.0 defines rules through PostgreSQL 18.
const PGCONFIG_RULES_VERSION: &str = "18";

pub(super) fn install(directory: &Path) -> Result<()> {
    let mut system = System::new();
    system.refresh_memory();
    let mut memory = system.total_memory();
    if let Some(limits) = system.cgroup_limits() {
        memory = memory.min(limits.total_memory);
    }
    if memory == 0 {
        // initdb already selected settings usable on this host.
        return Ok(());
    }

    let directory = directory.canonicalize()?;
    let disks = Disks::new_with_refreshed_list();
    let disk_type = disks
        .iter()
        .filter_map(|disk| {
            // Normalize mount paths the same way as the data directory, including
            // the extended-length drive prefix returned by Windows canonicalize.
            let mount = disk.mount_point().canonicalize().ok()?;
            directory
                .starts_with(&mount)
                .then(|| (mount.components().count(), disk.kind()))
        })
        .max_by_key(|&(depth, _)| depth)
        .map(|(_, kind)| kind);
    let disk = match disk_type {
        Some(DiskKind::SSD) => DiskType::Ssd,
        // HDD and unidentified volumes both use the conservative I/O profile.
        _ => DiskType::Hdd,
    };
    let os = match std::env::consts::OS {
        "macos" => Os::Darwin,
        "windows" => Os::Windows,
        "linux" => Os::Linux,
        _ => Os::Unix,
    };
    let arch = if cfg!(all(target_os = "windows", target_arch = "aarch64")) {
        // This release ships an x64 PostgreSQL binary on Windows ARM64.
        Arch::Amd64
    } else {
        match std::env::consts::ARCH {
            "aarch64" => Arch::Arm64,
            "arm" => Arch::Arm,
            "x86" => Arch::X86,
            _ => Arch::Amd64,
        }
    };
    let cpus = std::thread::available_parallelism().map_or(1, |count| count.get() as u32);
    let configuration = render(memory, cpus, os, arch, disk)?;
    write_profile(&directory, &configuration)
}

fn write_profile(directory: &Path, configuration: &str) -> Result<()> {
    fs::write(directory.join(CONFIG_NAME), configuration)?;
    // initdb emits active assignments. Place the include after them so the
    // generated profile applies, with room for manual overrides below it.
    writeln!(
        OpenOptions::new()
            .append(true)
            .open(directory.join("postgresql.conf"))?,
        "\ninclude = '{CONFIG_NAME}'\n# Add local overrides below this line."
    )?;
    Ok(())
}

fn render(memory: u64, cpus: u32, os: Os, arch: Arch, disk: DiskType) -> Result<String> {
    let request = TuningRequest {
        total_ram: Bytes::parse(&format!("{memory}B"))?,
        total_cpu: NonZeroU32::new(cpus).context("no logical CPU available to PostgreSQL")?,
        postgres_version: PgVersion::parse(PGCONFIG_RULES_VERSION)?,
        profile: Some(Profile::Desktop),
        disk_type: Some(disk),
        os: Some(os),
        arch: Some(arch),
        max_connections: None,
    };
    let mut result = pgconfig::tune(&request);
    // PostgreSQL 19 replaces the fixed worker count with lower and upper
    // bounds. Keep the worker budget selected by the Desktop profile.
    if let Some(workers) = result.recommendations.remove("io_workers") {
        result
            .recommendations
            .insert("io_min_workers", workers.clone());
        result.recommendations.insert("io_max_workers", workers);
    }
    let mut config = format!(
        "# Generated by Pioneer with PGConfig 4.0.0, profile {} (PostgreSQL {PGCONFIG_RULES_VERSION} rules)\n\
         # PGConfig RAM input: {memory} B, logical CPUs: {cpus}\n\
         # OS: {}, PostgreSQL architecture: {}, storage: {}, connections: {}\n",
        result.request.profile.as_str(),
        os.as_str(),
        arch.as_str(),
        disk.as_str(),
        result.request.max_connections,
    );
    for (name, setting) in result.recommendations {
        writeln!(config, "{name} = '{}'", setting.value)?;
    }
    Ok(config)
}

#[cfg(test)]
mod tests {
    use super::*;

    const GIB: u64 = 1024 * 1024 * 1024;

    #[test]
    fn renders_the_desktop_profile_for_bundled_postgres() -> Result<()> {
        let config = render(16 * GIB, 8, Os::Darwin, Arch::Arm64, DiskType::Ssd)?;
        let assignments: Vec<_> = config
            .lines()
            .filter(|line| !line.starts_with('#'))
            .collect();
        // PGConfig 4.0.0 output for 16 GB, with the I/O worker settings adapted for PostgreSQL 19.
        assert_eq!(
            assignments,
            [
                "checkpoint_completion_target = '0.9'",
                "effective_cache_size = '2GB'",
                "effective_io_concurrency = '200'",
                "file_copy_method = 'copy'",
                "io_max_combine_limit = '16'",
                "io_max_concurrency = '64'",
                "io_max_workers = '2'",
                "io_method = 'worker'",
                "io_min_workers = '2'",
                "maintenance_io_concurrency = '200'",
                "maintenance_work_mem = '164MB'",
                "max_connections = '100'",
                "max_parallel_workers = '8'",
                "max_parallel_workers_per_gather = '2'",
                "max_wal_size = '2GB'",
                "max_worker_processes = '8'",
                "min_wal_size = '512MB'",
                "random_page_cost = '1.1'",
                "shared_buffers = '1GB'",
                "wal_buffers = '-1'",
                "work_mem = '3MB'",
            ]
        );
        Ok(())
    }

    #[test]
    fn applies_the_generated_profile_after_initdb_defaults() -> Result<()> {
        let directory = tempfile::tempdir()?;
        let config = directory.path().join("postgresql.conf");
        fs::write(&config, "shared_buffers = 128MB\nmax_connections = 100\n")?;
        write_profile(directory.path(), "shared_buffers = '1GB'\n")?;
        assert_eq!(
            fs::read_to_string(config)?,
            "shared_buffers = 128MB\nmax_connections = 100\n\ninclude = 'pioneer-tuning.conf'\n# Add local overrides below this line.\n"
        );
        assert_eq!(
            fs::read_to_string(directory.path().join("pioneer-tuning.conf"))?,
            "shared_buffers = '1GB'\n"
        );
        Ok(())
    }

    #[test]
    fn uses_pgconfig_connection_limit_with_hdd_profile() -> Result<()> {
        let config = render(4 * GIB, 12, Os::Linux, Arch::Amd64, DiskType::Hdd)?;
        assert!(config.contains("max_connections = '100'"));
        assert!(config.contains("shared_buffers = '256MB'"));
        assert!(config.contains("work_mem = '839kB'"));
        assert!(config.contains("io_max_workers = '3'"));
        assert!(config.contains("io_min_workers = '3'"));
        assert!(config.contains("random_page_cost = '4.0'"));
        assert!(config.contains("effective_io_concurrency = '2'"));
        assert!(config.contains("maintenance_io_concurrency = '2'"));
        Ok(())
    }
}
