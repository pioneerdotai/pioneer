#!/usr/bin/env python3
"""Update the SDK, packaged driver and passive tool schemas from one CUA release.

No upstream code, daemon, schema generator or build is executed. Cargo only
resolves the lockfile. The scheduled workflow publishes a PR for normal CI.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tomllib
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
METADATA = Path("config/cua-driver.json")
CONSTANTS = Path("crates/protocol/src/cua_driver_release.rs")
GATEWAY = Path("crates/gateway/Cargo.toml")
CATALOG = Path("crates/tools/src/handlers/computer_use")
UPSTREAM = "https://github.com/trycua/cua"
WORKSPACE = "libs/cua-driver/rust/Cargo.toml"
NATIVE = "libs/cua-driver/contract/manifest.json"
BROWSER = "libs/cua-driver/rust/crates/cua-driver-core/src/browser/tools.rs"
BROWSER_MODULE = "libs/cua-driver/rust/crates/cua-driver-core/src/browser/mod.rs"
RELEASE_PATTERN = re.compile(r"(?:nightly-)?cua-driver-rs-v[0-9]+\.[0-9]+\.[0-9]+(?:-nightly\.[0-9.]+)?\Z")


def github(path, raw=False):
    headers = {"Accept": "application/vnd.github.raw+json" if raw else "application/vnd.github+json",
               "User-Agent": "pioneer-cua-updater", "X-GitHub-Api-Version": "2022-11-28"}
    token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = "Bearer " + token
    request = urllib.request.Request("https://api.github.com/repos/trycua/cua/" + path, headers=headers)
    with urllib.request.urlopen(request, timeout=60) as response:
        data = response.read()
    return data.decode() if raw else json.loads(data)


def select_release(releases):
    # Upstream marks numbered driver releases as prereleases as well. Match
    # this component's tags, not GitHub's repository-wide /releases/latest.
    candidates = [r for r in releases if not r.get("draft") and r.get("published_at")
                  and RELEASE_PATTERN.fullmatch(r["tag_name"])]
    if not candidates:
        raise ValueError("No published CUA driver release was found")
    return max(candidates, key=lambda r: r["published_at"])


def constants(metadata):
    return ("// Generated by scripts/update-cua-driver.py from config/cua-driver.json.\n"
            f'pub const CUA_DRIVER_RELEASE: &str = {json.dumps(metadata["release"])};\n'
            f'pub const CUA_DRIVER_REVISION: &str = {json.dumps(metadata["revision"])};\n'
            f'pub const CUA_DRIVER_VERSION: &str = {json.dumps(metadata["version"])};\n')


def supported_names(root):
    text = (root / "crates/protocol/src/turn.rs").read_text()
    names = text.split("pub const CUA_TOOL_NAMES: &[&str] = &[", 1)[1].split("];", 1)[0]
    return [name.removeprefix("cua_") for name in re.findall(r'"(cua_[a-z_]+)"', names)]


def fragment(text, start):
    """Copy one balanced Rust expression, ignoring comments and string contents."""
    tokens = re.compile(r'r(?P<hashes>\#*)".*?"(?P=hashes)|"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/|[(){}\[\]]', re.S)
    stack = []
    pairs = {"(": ")", "{": "}", "[": "]"}
    for match in tokens.finditer(text, start):
        token = match[0]
        if token in pairs:
            stack.append(pairs[token])
        elif token in pairs.values():
            if not stack or stack.pop() != token:
                raise ValueError("Unbalanced upstream schema expression")
            if not stack:
                return text[start:match.end()]
    raise ValueError("Unterminated upstream schema expression")


def browser_catalog(source, module, names, native, release):
    helpers = []
    for match in re.finditer(r"^fn schema_[a-z_]+\(\) -> Value \{", source, re.M):
        start = source.index("{", match.start())
        helpers.append(source[match.start():start] + fragment(source, start))
    session = re.search(r"pub\(crate\) fn session_schema\(\) -> serde_json::Value \{", module)
    if session is None:
        raise ValueError("Upstream session schema needs integration review")
    start = module.index("{", session.start())
    session_body = fragment(module, start)
    session_schema = next(t["input_schema"]["properties"]["session"] for t in native["tools"]
                          if "session" in t.get("input_schema", {}).get("properties", {}))
    session_body = session_body.replace("cua_driver_contract::MULTI_CALL_SESSION_DESCRIPTION",
                                        json.dumps(session_schema["description"], ensure_ascii=False))
    if "cua_driver_contract::" in session_body:
        raise ValueError("Upstream session schema needs integration review")
    helpers.append("fn schema_session() -> Value " + session_body)
    schemas = []
    for name in names:
        match = re.search(r'\bname:\s*"' + re.escape(name) + r'"\.into\(\)', source)
        if match is None:
            raise ValueError(f"Supported browser tool disappeared upstream: {name}")
        tail = source[match.end():]
        expression = re.search(r"\binput_schema:\s*json!\(", tail)
        next_tool = re.search(r'\bname:\s*"[a-z_]+"\.into\(\)', tail)
        if expression is None or (next_tool is not None and next_tool.start() < expression.start()):
            raise ValueError(f"Cannot extract schema for {name}")
        start = match.end() + expression.end() - 1
        schemas.append(f'({json.dumps(name)}, json!{fragment(source, start)}),')
    generated = (f"// Generated from trycua/cua release {release} (MIT).\n"
                 "// Only passive schema expressions; Gateway retains its explicit operation allowlist.\n"
                 "use serde_json::{Value, json};\n" + "\n\n".join(helpers)
                 + "\npub(super) fn schemas() -> Vec<(&'static str, Value)> {\nvec![\n"
                 + "\n".join(schemas) + "\n]\n}\n")
    return subprocess.check_output(["rustfmt", "--edition", "2024", "--emit", "stdout"],
                                   input=generated, text=True)


def check(root):
    metadata = json.loads((root / METADATA).read_text())
    if metadata["channel"] != "latest-published" or not RELEASE_PATTERN.fullmatch(metadata["release"]):
        raise ValueError("Invalid CUA release channel or tag")
    if not re.fullmatch("[0-9a-f]{40}", metadata["revision"]):
        raise ValueError("Invalid resolved CUA revision")
    if (root / CONSTANTS).read_text() != constants(metadata):
        raise ValueError("CUA release constants are out of sync")
    dependency = tomllib.loads((root / GATEWAY).read_text())["dependencies"]["cua-driver-sdk"]
    if dependency.get("tag") != metadata["release"] or dependency.get("git") != UPSTREAM or "rev" in dependency:
        raise ValueError("SDK must use the selected upstream release tag")
    native = json.loads((root / CATALOG / "native-contract.json").read_text())
    if native["revision"] != metadata["revision"]:
        raise ValueError("Native schemas are from another CUA release")
    names = supported_names(root)
    if {t["name"] for t in native["tools"]} != {n for n in names if not n.startswith("browser_") and n != "get_browser_state"}:
        raise ValueError("Native schemas do not match the existing operation allowlist")
    browser = (root / CATALOG / "browser_catalog.rs").read_text()
    if not browser.startswith(f'// Generated from trycua/cua release {metadata["release"]} (MIT).'):
        raise ValueError("Browser schemas are from another CUA release")
    packages = tomllib.loads((root / "Cargo.lock").read_text())["package"]
    sources = {p["source"] for p in packages if p.get("source", "").startswith("git+" + UPSTREAM + "?")}
    expected = f'git+{UPSTREAM}?tag={urllib.parse.quote(metadata["release"], safe="")}#{metadata["revision"]}'
    if sources != {expected}:
        raise ValueError("Cargo.lock CUA source differs from the selected release")
    print(f'CUA release is coherent: {metadata["release"]} ({metadata["revision"][:8]})')


def update(root, release=None):
    if release is None:
        # This component publishes frequently; paginate if other components fill
        # the first page. Each response is ordered by newest releases first.
        for page in range(1, 21):
            releases = github(f"releases?per_page=100&page={page}")
            if not releases:
                raise ValueError("No CUA driver release found")
            try:
                release = select_release(releases)["tag_name"]
                break
            except ValueError:
                continue
    if release is None or not RELEASE_PATTERN.fullmatch(release):
        raise ValueError("Expected a published CUA driver release tag")
    published = github("releases/tags/" + urllib.parse.quote(release, safe=""))
    if published.get("draft") or not published.get("published_at"):
        raise ValueError("CUA release is not published")
    revision = github("commits/" + urllib.parse.quote(release, safe=""))["sha"]
    if not re.fullmatch("[0-9a-f]{40}", revision):
        raise ValueError("Invalid CUA release commit")
    previous = json.loads((root / METADATA).read_text()) if (root / METADATA).exists() else None
    if previous and previous["release"] == release:
        if previous["revision"] != revision:
            raise ValueError("Upstream moved an existing release tag; refusing silent replacement")
        check(root)
        return
    paths = [WORKSPACE, NATIVE, BROWSER, BROWSER_MODULE]
    sources = {p: github(f"contents/{p}?ref={revision}", raw=True) for p in paths}
    version = tomllib.loads(sources[WORKSPACE])["workspace"]["package"]["version"]
    native = json.loads(sources[NATIVE])
    metadata = dict(channel="latest-published", release=release, revision=revision, version=version,
                    published_at=published["published_at"], contract_version=native["contract_version"],
                    source_sha256={p: hashlib.sha256(sources[p].encode()).hexdigest() for p in paths})
    names = supported_names(root)
    native_names = [n for n in names if not n.startswith("browser_") and n != "get_browser_state"]
    by_name = {t["name"]: t for t in native["tools"]}
    selected = [{k: by_name[n][k] for k in ("name", "description", "input_schema")} for n in native_names]
    browser = browser_catalog(sources[BROWSER], sources[BROWSER_MODULE],
                              [n for n in names if n not in native_names], native, release)
    gateway = (root / GATEWAY).read_text()
    gateway, count = re.subn(r'(cua-driver-sdk = \{ git = "https://github.com/trycua/cua", )(?:rev|tag) = "[^"]+"',
                             lambda m: m[1] + 'tag = ' + json.dumps(release), gateway)
    if count != 1:
        raise ValueError("Cannot locate SDK dependency")
    outputs = {METADATA: json.dumps(metadata, indent=2) + "\n", CONSTANTS: constants(metadata),
               GATEWAY: gateway, CATALOG / "browser_catalog.rs": browser,
               CATALOG / "native-contract.json": json.dumps(dict(revision=revision, tools=selected, license="MIT", source=NATIVE), indent=2) + "\n"}
    originals = {p: (root / p).read_bytes() if (root / p).exists() else None for p in [*outputs, Path("Cargo.lock")]}
    try:
        for path, text in outputs.items():
            (root / path).write_text(text)
        subprocess.run(["cargo", "update", "--workspace"], cwd=root, check=True)
        check(root)
    except BaseException:
        for path, data in originals.items():
            if data is None:
                (root / path).unlink(missing_ok=True)
            else:
                (root / path).write_bytes(data)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check committed metadata without network or Cargo")
    parser.add_argument("--release", help="select a specific published driver tag instead of the newest")
    args = parser.parse_args()
    if args.check:
        check(ROOT)
    else:
        update(ROOT, args.release)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"CUA update failed: {error}", file=sys.stderr)
        sys.exit(1)
